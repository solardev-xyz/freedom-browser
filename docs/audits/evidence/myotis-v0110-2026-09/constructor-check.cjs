const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const a = require(path.resolve(process.argv[2]));
const root = '0x' + '11'.repeat(32), other = '0x' + '22'.repeat(32);
const base = fs.mkdtempSync(path.join(os.tmpdir(), 'myotis442-check-'));
const results = { revision: 'v0.1.10 official darwin-arm64 addon', base, checks: [], findings: [] };
assert.equal(a.init(), 26);
const invalid = path.join(base, 'invalid');
for (const slot of [NaN, Infinity, -1, 0, 1.5, Number.MAX_SAFE_INTEGER + 1, Number.MAX_SAFE_INTEGER]) assert.equal(a.createWithCheckpoint('gnosis', invalid, root, slot), -1);
for (const r of ['0x00', '0x' + '00'.repeat(32), '0x' + 'gg'.repeat(32)]) assert.equal(a.createWithCheckpoint('gnosis', invalid, r, 1), -1);
assert.equal(a.createWithCheckpoint('unknown', invalid, root, 1), -1);
assert.equal(a.createWithCheckpoint('gnosis', '', root, 1), -1);
assert.equal(fs.existsSync(invalid), false);
results.checks.push('ABI 26; invalid input rejected without creating directory');
for (const net of ['mainnet', 'gnosis', 'sepolia']) {
 const dir = path.join(base, net), suffix = net === 'mainnet' ? '' : '-' + net;
 const h = a.createWithCheckpoint(net, dir, root, 100); assert.ok(h > 0);
 assert.equal(a.createWithCheckpoint(net, dir, root, 100), -1);
 a.stop(h);
 const marker = path.join(dir, 'sync-anchor' + suffix + '.json');
 const before = fs.readFileSync(marker);
 assert.equal(a.createWithCheckpoint(net, dir, other, 100), -3);
 assert.equal(a.createWithCheckpoint(net, dir, root, 101), -3);
 assert.equal(a.create(net, dir), -3);
 assert.deepEqual(fs.readFileSync(marker), before);
 fs.writeFileSync(path.join(dir, 'sync-state' + suffix + '.snapshot'), 'constructor fixture');
 const resumed = a.createWithCheckpoint(net, dir, root, 100); assert.ok(resumed > 0); a.stop(resumed);
 const fresh = path.join(base, 'foreign-' + net); fs.mkdirSync(fresh);
 fs.writeFileSync(path.join(fresh, 'sync-state' + suffix + '.snapshot'), 'foreign fixture');
 assert.equal(a.createWithCheckpoint(net, fresh, root, 100), -3);
 assert.equal(fs.existsSync(path.join(fresh, 'sync-anchor' + suffix + '.json')), false);
 fs.writeFileSync(marker, '{bad');
 assert.equal(a.createWithCheckpoint(net, dir, root, 100), -3);
 assert.equal(a.create(net, dir), -3);
 results.checks.push(net + ': fresh import, active-handle refusal, same-anchor restart, mismatch/foreign snapshot/invalid marker refusal');
}
// Review repros: no node starts, no networking, only disposable directories.
const real = path.join(base, 'real'); const alias = path.join(base, 'alias');
const first = a.create('mainnet', real); assert.ok(first > 0);
fs.symlinkSync(real, alias, 'dir');
const second = a.createWithCheckpoint('mainnet', alias, root, 100);
results.findings.push({ case: 'symlink alias to directory owned by live embedded-anchor handle', expected: -1, actual: second, markerWritten: fs.existsSync(path.join(real, 'sync-anchor.json')) });
assert.equal(second, -1); assert.equal(fs.existsSync(path.join(real, 'sync-anchor.json')), false); a.stop(first);
const dangling = path.join(base, 'dangling'); fs.mkdirSync(dangling);
const marker = path.join(dangling, 'sync-anchor.json'); fs.symlinkSync(path.join(base, 'missing-marker-target'), marker);
const third = a.createWithCheckpoint('mainnet', dangling, root, 100);
results.findings.push({ case: 'dangling marker symlink treated as absent', expected: -3, actual: third, symlinkReplaced: !fs.lstatSync(marker).isSymbolicLink() });
assert.equal(third, -3); assert.equal(fs.lstatSync(marker).isSymbolicLink(), true);
if (process.argv[3]) fs.writeFileSync(process.argv[3], JSON.stringify(results, null, 2));
console.log(JSON.stringify(results, null, 2));
process.exit(0);
